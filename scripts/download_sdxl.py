"""Download SDXL Faces into a held-out-only evaluation manifest.

Source: https://huggingface.co/datasets/8clabs/sdxl-faces
License declared in dataset card: MIT. All images are generated by SDXL.
No image is included in training or checkpoint selection.
"""
import argparse
import csv
import json
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from urllib.request import urlopen

REPO = 'https://huggingface.co/datasets/8clabs/sdxl-faces/resolve/main/'
API = 'https://huggingface.co/api/datasets/8clabs/sdxl-faces'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--output', default='/workspace/data/sdxl_faces')
    parser.add_argument('--manifest', default='/workspace/data/sdxl_external.csv')
    parser.add_argument('--workers', type=int, default=16)
    args = parser.parse_args()
    output = Path(args.output)
    output.mkdir(parents=True, exist_ok=True)
    with urlopen(API, timeout=60) as r:
        metadata = json.load(r)
    assert metadata.get('gated') is False, 'Dataset must not require gated access.'
    assert metadata.get('cardData', {}).get('license') == 'mit', 'Verify license before download.'
    files = sorted(x['rfilename'] for x in metadata['siblings'] if x['rfilename'].startswith('imgs/') and x['rfilename'].endswith('.png'))
    if len(files) != 1920:
        raise RuntimeError(f'Expected 1920 SDXL images, found {len(files)}; inspect dataset update before training.')

    def fetch(name):
        target = output / Path(name).name
        if not target.exists():
            data = urlopen(REPO + name, timeout=120).read()
            temp = target.with_suffix('.tmp')
            temp.write_bytes(data)
            temp.replace(target)
        return str(target)

    with ThreadPoolExecutor(max_workers=args.workers) as pool:
        for i, path in enumerate(pool.map(fetch, files), 1):
            if i % 200 == 0:
                print(f'Downloaded/verified {i}/{len(files)}', flush=True)

    with open(args.manifest, 'w', newline='', encoding='utf-8') as f:
        writer = csv.writer(f)
        writer.writerow(['path', 'label', 'source', 'split', 'identity'])
        for name in files:
            writer.writerow([str(output / Path(name).name), 1, 'sdxl_faces_external', 'external', Path(name).stem])
    print(f'SDXL external manifest: {len(files)} fake images -> {args.manifest}', flush=True)


if __name__ == '__main__':
    main()
